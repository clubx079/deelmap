-- Comment insert: derive ltree path + depth, +1 equity, bump post comment_count
create or replace function public.community_comments_before_insert()
returns trigger language plpgsql as $$
declare
  v_parent_path  ltree;
  v_parent_depth int;
  v_label        text;
begin
  -- ltree labels must match [A-Za-z0-9_]; uuid hyphens are not allowed.
  v_label := replace(NEW.id::text, '-', '_');
  if NEW.parent_id is null then
    NEW.path  := ('root.' || v_label)::ltree;
    NEW.depth := 0;
  else
    select path, depth into v_parent_path, v_parent_depth
      from public.community_comments where id = NEW.parent_id;
    if v_parent_path is null then
      raise exception 'Parent comment % not found', NEW.parent_id;
    end if;
    NEW.path  := v_parent_path || v_label::ltree;
    NEW.depth := least(v_parent_depth + 1, 8);
  end if;
  return NEW;
end $$;

create trigger trg_community_comments_before_insert
  before insert on public.community_comments
  for each row execute function public.community_comments_before_insert();

