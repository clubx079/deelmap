-- Reddit-style hot score (~12hr half-life via 45000 divisor against epoch seconds)
create or replace function public.community_hot_score(p_score int, p_created_at timestamptz)
returns double precision language sql immutable as $$
  select
    log(greatest(abs(p_score), 1)) * sign(p_score)::double precision
    + extract(epoch from (p_created_at - timestamp '2025-01-01 00:00:00')) / 45000.0
$$;

-- Award equity: append to ledger, bump denormalized score, recompute tier.
-- Self-vote exclusion is the CALLER's responsibility (see vote trigger below).
create or replace function public.community_award_equity(
  p_profile_id uuid,
  p_delta      int,
  p_reason     text,
  p_ref_type   text default null,
  p_ref_id     text default null
) returns void language plpgsql as $$
declare
  v_new_score int;
  v_tier_id   bigint;
begin
  if p_delta = 0 or p_profile_id is null then return; end if;

  insert into public.community_equity_events (profile_id, delta, reason, ref_type, ref_id)
  values (p_profile_id, p_delta, p_reason, p_ref_type, p_ref_id);

  update public.community_profiles
    set equity_score = equity_score + p_delta
    where id = p_profile_id
    returning equity_score into v_new_score;

  select id into v_tier_id from public.community_tiers
    where min_equity <= v_new_score
    order by min_equity desc limit 1;

  update public.community_profiles set tier_id = v_tier_id where id = p_profile_id;
end $$;

-- Apply vote: insert / update / clear (value = 0). Idempotent.
create or replace function public.community_apply_vote(
  p_profile_id  uuid,
  p_target_type text,
  p_target_id   uuid,
  p_value       smallint
) returns smallint language plpgsql as $$
declare
  v_existing smallint;
begin
  select value into v_existing
    from public.community_votes
    where profile_id = p_profile_id
      and target_type = p_target_type
      and target_id = p_target_id;

  if p_value = 0 then
    delete from public.community_votes
      where profile_id = p_profile_id
        and target_type = p_target_type
        and target_id = p_target_id;
    return 0;
  end if;

  insert into public.community_votes (profile_id, target_type, target_id, value)
  values (p_profile_id, p_target_type, p_target_id, p_value)
  on conflict (profile_id, target_type, target_id)
    do update set value = excluded.value, created_at = now();
  return p_value;
end $$;

-- Vote trigger: maintain target score + hot_score, award equity (excluding self-votes)
create or replace function public.community_votes_after_change()
returns trigger language plpgsql as $$
declare
  v_author     uuid;
  v_created_at timestamptz;
  v_delta_score int;
  v_old_eq     int;
  v_new_eq     int;
  v_eq_delta   int;
begin
  if TG_OP = 'INSERT' then
    v_delta_score := NEW.value;
  elsif TG_OP = 'UPDATE' then
    v_delta_score := NEW.value - OLD.value;
  else  -- DELETE
    v_delta_score := -OLD.value;
  end if;

  if NEW.target_type is not null then
    if NEW.target_type = 'post' then
      update public.community_posts
        set score = score + v_delta_score,
            hot_score = public.community_hot_score(score + v_delta_score, created_at)
        where id = NEW.target_id
        returning author_id, created_at into v_author, v_created_at;
    else
      update public.community_comments
        set score = score + v_delta_score
        where id = NEW.target_id
        returning author_id into v_author;
    end if;
  else
    if OLD.target_type = 'post' then
      update public.community_posts
        set score = score + v_delta_score,
            hot_score = public.community_hot_score(score + v_delta_score, created_at)
        where id = OLD.target_id
        returning author_id into v_author;
    else
      update public.community_comments
        set score = score + v_delta_score
        where id = OLD.target_id
        returning author_id into v_author;
    end if;
  end if;

  -- Equity scoring (self-vote excluded)
  if v_author is not null then
    declare v_voter uuid := coalesce(NEW.profile_id, OLD.profile_id);
            v_ttype text := coalesce(NEW.target_type, OLD.target_type);
            v_old   smallint := coalesce(OLD.value, 0);
            v_new   smallint := coalesce(NEW.value, 0);
            v_old_pts int;
            v_new_pts int;
    begin
      if v_voter <> v_author then
        -- per-vote equity: post +5/-2, comment +2/-1
        v_old_pts := case v_old when 1 then case when v_ttype='post' then 5 else 2 end
                              when -1 then case when v_ttype='post' then -2 else -1 end
                              else 0 end;
        v_new_pts := case v_new when 1 then case when v_ttype='post' then 5 else 2 end
                              when -1 then case when v_ttype='post' then -2 else -1 end
                              else 0 end;
        v_eq_delta := v_new_pts - v_old_pts;
        if v_eq_delta <> 0 then
          perform public.community_award_equity(v_author, v_eq_delta,
            'vote_' || v_ttype, v_ttype, coalesce(NEW.target_id, OLD.target_id)::text);
        end if;
      end if;
    end;
  end if;

  return null;
end $$;

create trigger trg_community_votes_after_change
  after insert or update or delete on public.community_votes
  for each row execute function public.community_votes_after_change();

